def set_text(p, text):
    p.runs[0].text = text
    for r in p.runs[1:]:
        r.text = ""


def fill(p, items):
    """Заменяет абзац-заглушку p на список абзацев.

    Элемент списка – строка (обычный абзац с отступом первой строки),
    ("img", путь) – рисунок, ("cap", текст) – подпись по центру.
    """
    anchor = p
    first = True
    for item in items:
        if first:
            new = p
            first = False
        else:
            el = copy.deepcopy(p._p)
            anchor._p.addnext(el)
            new = docx.text.paragraph.Paragraph(el, p._parent)
        for r in new.runs[1:]:
            r._r.getparent().remove(r._r)
        run = new.runs[0]
        if isinstance(item, tuple) and item[0] == "img":
            run.text = ""
            run.add_picture(str(item[1]), width=Cm(16))
            new.alignment = WD_ALIGN_PARAGRAPH.CENTER
        elif isinstance(item, tuple) and item[0] == "cap":
            run.text = item[1]
            run.italic = True
            new.alignment = WD_ALIGN_PARAGRAPH.CENTER
        else:
            run.text = "\t" + item
            new.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        anchor = new


